"""Compare portal-entry artifacts with the baseline captured before the renderer cutovers (#1199).

``tests/fixtures/portal_parity_baseline.json`` holds one record per case, captured
once at the commit its ``provenance`` names (apart from the command records #1289,
#1359, #1363 and #1361 re-captured, the 58 records #1360 re-captured, the 33
records #1379 re-captured and the 42 records #1383 re-captured, beside the 16
it deleted, the two records #1385 added, the seven records #1427 and
again #1446 re-captured and the record #1447 re-captured; see
docs/architecture.md) and never regenerated by the tests:
comparing two runs of the code under test is not baseline parity. A record
holds a file's SHA-256 and size; a ZIP package (an XLSX) also lists its
members in order, each as ``"<name> <CRC-32> <size>"``.

:func:`fix_xlsx_clock` pins the three clock reads that make openpyxl's bytes
time-dependent, so a workbook's complete raw bytes, ``docProps/core.xml``
included, can be compared. It changes no production code.

The workbook records hold stock zlib's deflate output; zlib 1.3.1 and 1.3.2
compress identically. A distribution's Python may link zlib-ng, which
compresses differently, so its workbook byte checks fail and name the zlib
build. Run local 3.13 and 3.14 suites on uv-managed CPython
(``uv python install 3.14``, ``--managed-python``).

CI uses uv-managed CPython 3.13 for same-repository pull requests and
3.12, 3.13 and 3.14 for pushes to main.
"""

from __future__ import annotations

import functools
import hashlib
import json
import os
import zipfile
import zlib
from datetime import datetime, timezone
from io import BytesIO
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import openpyxl.packaging.core
import openpyxl.writer.excel
import pytest

BASELINE = Path(__file__).parent / "fixtures" / "portal_parity_baseline.json"

# The instant every workbook's created and modified times, and its ZIP member
# times, read under fix_xlsx_clock. ZIP stores seconds in steps of two.
FIXED_INSTANT = datetime(2026, 4, 1, 9, 30, 0)

# The complete docProps/core.xml openpyxl writes under fix_xlsx_clock.
CORE_PROPERTIES = (
    b"<cp:coreProperties"
    b' xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties"'
    b' xmlns:dc="http://purl.org/dc/elements/1.1/"'
    b' xmlns:dcterms="http://purl.org/dc/terms/"'
    b' xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
    b"<dc:creator>openpyxl</dc:creator>"
    b'<dcterms:created xsi:type="dcterms:W3CDTF">2026-04-01T09:30:00Z</dcterms:created>'
    b'<dcterms:modified xsi:type="dcterms:W3CDTF">2026-04-01T09:30:00Z</dcterms:modified>'
    b"</cp:coreProperties>"
)
_ZIP_MAGIC = b"PK\x03\x04"


class _FixedDatetime(datetime):
    @classmethod
    def now(cls, tz: Any = None) -> datetime:
        return FIXED_INSTANT.replace(tzinfo=tz)


def fix_xlsx_clock(monkeypatch: pytest.MonkeyPatch) -> None:
    """Make openpyxl's created and modified times and zipfile's member times
    :data:`FIXED_INSTANT`.

    openpyxl reads ``datetime.datetime.now`` when it builds a workbook and
    again when it saves one; :meth:`zipfile.ZipFile.writestr` stamps each member
    with ``time.localtime(time.time())``. Missing clock attributes fail here;
    complete workbook-byte comparisons catch unpatched clock reads.
    """
    clock = SimpleNamespace(datetime=_FixedDatetime, timezone=timezone)
    monkeypatch.setattr(openpyxl.packaging.core, "datetime", clock)
    monkeypatch.setattr(openpyxl.writer.excel, "datetime", clock)
    frozen = FIXED_INSTANT.timetuple()
    monkeypatch.setattr(
        zipfile,
        "time",
        SimpleNamespace(time=lambda: 0.0, localtime=lambda _seconds=None: frozen),
    )


def file_record(data: bytes) -> dict[str, Any]:
    """The record of one file's bytes, as the baseline stores it."""
    record: dict[str, Any] = {"sha256": hashlib.sha256(data).hexdigest(), "size": len(data)}
    if data.startswith(_ZIP_MAGIC):
        with zipfile.ZipFile(BytesIO(data)) as package:
            record["members"] = [
                f"{info.filename} {info.CRC:08x} {info.file_size}" for info in package.infolist()
            ]
    return record


def tree_records(root: Path) -> dict[str, dict[str, Any]]:
    """The record of every file under ``root``, keyed by its POSIX path below
    ``root``. Hidden files, such as a staging file left behind, count."""

    def fail(error: OSError) -> None:
        raise error

    records: dict[str, dict[str, Any]] = {}
    for directory, _dirs, files in os.walk(root, onerror=fail):
        for name in files:
            path = Path(directory) / name
            records[path.relative_to(root).as_posix()] = file_record(path.read_bytes())
    return dict(sorted(records.items()))


@functools.cache
def _baseline() -> dict[str, Any]:
    return json.loads(BASELINE.read_text(encoding="utf-8"))


def expected(group: str, case: str) -> Any:
    """The baseline record of ``case`` in ``group``."""
    return _baseline()[group][case]


def baseline_cases(group: str) -> set[str]:
    """The cases ``group`` of the baseline has records for."""
    return set(_baseline()[group])


def _assert_record_matches(actual: dict[str, Any], record: dict[str, Any]) -> None:
    # A package's member list is compared first, so a mismatch names the member
    # that changed; equal members with unequal bytes mean only the compression
    # or the ZIP headers differ (a different zlib build, for one).
    if "members" in actual or "members" in record:
        assert actual.get("members") == record.get("members"), "package members differ"
    assert actual == record, (
        "every package member matches; the compressed bytes or ZIP headers differ"
        f" (this Python links zlib {zlib.ZLIB_RUNTIME_VERSION}; the baseline holds"
        " stock zlib's deflate output, which zlib-ng does not reproduce)"
        if "members" in actual
        else "file bytes differ"
    )


def assert_file_matches(data: bytes, record: dict[str, Any]) -> None:
    """Assert ``data`` has exactly the baseline bytes ``record`` describes."""
    _assert_record_matches(file_record(data), record)


def assert_workbook_matches(data: bytes, record: dict[str, Any]) -> None:
    """:func:`assert_file_matches`, after checking the complete core properties."""
    with zipfile.ZipFile(BytesIO(data)) as package:
        assert package.read("docProps/core.xml") == CORE_PROPERTIES
    assert_file_matches(data, record)


def run_record(exit_code: int, out: str, err: str, outputs: Path, tmp_path: Path) -> dict[str, Any]:
    """The record of one command run: its exit code, its streams as lines
    that keep their line endings, with ``tmp_path`` written as ``<tmp>``, and
    every file under ``outputs``."""
    tmp = str(tmp_path)
    return {
        "exit_code": exit_code,
        "stdout": out.replace(tmp, "<tmp>").splitlines(keepends=True),
        "stderr": err.replace(tmp, "<tmp>").splitlines(keepends=True),
        "outputs": tree_records(outputs),
    }


def assert_run_matches(run: dict[str, Any], record: dict[str, Any]) -> None:
    """Assert a :func:`run_record` equals the baseline ``record``: the same
    exit code, streams (line endings included) and output files, each byte
    for byte."""
    assert sorted(run["outputs"]) == sorted(record["outputs"]), "the set of output files differs"
    for name, output in record["outputs"].items():
        _assert_record_matches(run["outputs"][name], output)
    assert run == record
